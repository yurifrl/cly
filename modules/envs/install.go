package envs

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"
)

// Plain stderr message helpers matching the module's ✓/⚠/✗ output style.
func msgInfo(format string, a ...any)    { fmt.Fprintf(os.Stderr, format+"\n", a...) }
func msgSuccess(format string, a ...any) { fmt.Fprintf(os.Stderr, "✓ "+format+"\n", a...) }
func msgError(format string, a ...any)   { fmt.Fprintf(os.Stderr, "✗ "+format+"\n", a...) }

var installCmd = &cobra.Command{
	Use:   "install [fish|bash|zsh]",
	Short: "Install shell integration for envs loading at startup",
	Long: `Install shell integration that loads envs from the local cache at startup.
If no shell is specified, detects the current shell automatically.
After installing, populates the cache from 1Password if empty.`,
	Args:      cobra.MaximumNArgs(1),
	ValidArgs: []string{"fish", "bash", "zsh"},
	RunE:      runInstall,
}

func runInstall(cmd *cobra.Command, args []string) error {
	shell := ""
	if len(args) > 0 {
		shell = strings.ToLower(args[0])
	} else {
		shell = detectShell()
		if shell == "" {
			return fmt.Errorf("could not detect shell, specify one: cly envs install [fish|bash|zsh]")
		}
		msgInfo("Detected shell: %s", shell)
	}

	switch shell {
	case "fish":
		if err := installFish(); err != nil {
			return err
		}
	case "bash":
		if err := installBash(); err != nil {
			return err
		}
	case "zsh":
		if err := installZsh(); err != nil {
			return err
		}
	default:
		return fmt.Errorf("unsupported shell: %s (use fish, bash, or zsh)", shell)
	}

	// Populate cache if empty
	if _, err := cacheReadAll(); err != nil {
		msgInfo("Populating cache from 1Password...")
		config := LoadConfig()
		fields, fetchErr := fetchFromOP(context.Background(), config, true)
		if fetchErr != nil {
			msgError("Could not fetch from 1Password: %v", fetchErr)
			msgInfo("Run 'cly envs' later to populate the cache")
		} else {
			if err := cacheStoreAll(fields); err != nil {
				msgError("Cache store failed: %v", err)
			} else {
				msgSuccess("Cached %d variables in %s", len(fields), cacheLabel())
			}
		}
	}

	return nil
}

func detectShell() string {
	// Check SHELL env var
	shell := os.Getenv("SHELL")
	if strings.Contains(shell, "fish") {
		return "fish"
	}
	if strings.Contains(shell, "zsh") {
		return "zsh"
	}
	if strings.Contains(shell, "bash") {
		return "bash"
	}
	return ""
}

func installFish() error {
	home, err := os.UserHomeDir()
	if err != nil {
		return err
	}

	dir := filepath.Join(home, ".config", "fish", "conf.d")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}

	content := `# cly envs — load environment variables from the local cache at shell startup.
# Generated by "cly envs install fish". Do not edit by hand.
# Reads from the cache (instant). Run "cly envs" to refresh from 1Password.
if command -q cly
    cly envs --fish 2>/dev/null | source
end
`
	path := filepath.Join(dir, "cly-envs.fish")
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		return err
	}
	msgSuccess("Installed %s", path)
	msgInfo("Restart your shell or run: source %s", path)
	return nil
}

func installBash() error {
	home, err := os.UserHomeDir()
	if err != nil {
		return err
	}

	snippet := `
# cly envs — load environment variables from the local cache at shell startup.
# Generated by "cly envs install bash". Remove this block to uninstall.
# Reads from the cache (instant). Run "cly envs" to refresh from 1Password.
if command -v cly >/dev/null 2>&1; then
    eval "$(cly envs --plain 2>/dev/null)"
fi
`
	rcPath := filepath.Join(home, ".bashrc")
	return appendToRC(rcPath, snippet, "cly envs")
}

func installZsh() error {
	home, err := os.UserHomeDir()
	if err != nil {
		return err
	}

	snippet := `
# cly envs — load environment variables from the local cache at shell startup.
# Generated by "cly envs install zsh". Remove this block to uninstall.
# Reads from the cache (instant). Run "cly envs" to refresh from 1Password.
if command -v cly >/dev/null 2>&1; then
    eval "$(cly envs --plain 2>/dev/null)"
fi
`
	rcPath := filepath.Join(home, ".zshrc")
	return appendToRC(rcPath, snippet, "cly envs")
}

func appendToRC(path, snippet, marker string) error {
	if data, err := os.ReadFile(path); err == nil {
		if strings.Contains(string(data), marker) {
			msgInfo("Already installed in %s (found %q marker)", path, marker)
			return nil
		}
	}

	f, err := os.OpenFile(path, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
	if err != nil {
		return fmt.Errorf("open %s: %w", path, err)
	}
	defer func() { _ = f.Close() }()

	if _, err := f.WriteString(snippet); err != nil {
		return err
	}
	msgSuccess("Installed to %s", path)
	msgInfo("Restart your shell or run: source %s", path)
	return nil
}
